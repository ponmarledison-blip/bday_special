const cv = $("confetti"),
  ctx = cv.getContext("2d");
let parts = [],
  raf = 0;
const colors = ["#ff5c9a", "#d6286f", "#ffb3d1", "#ffc93c", "#fffafb"];
function size() {
  cv.width = innerWidth * devicePixelRatio;
  cv.height = innerHeight * devicePixelRatio;
}
addEventListener("resize", size);
size();
function burst() {
  if (REDUCED) return;
  for (let i = 0; i < 150; i++) {
    parts.push({
      x: Math.random() * cv.width,
      y: -20 * devicePixelRatio - Math.random() * cv.height * 0.4,
      vx: (Math.random() - 0.5) * 3,
      vy: 2 + Math.random() * 4,
      w: (6 + Math.random() * 8) * devicePixelRatio,
      h: (4 + Math.random() * 6) * devicePixelRatio,
      r: Math.random() * 6,
      vr: (Math.random() - 0.5) * 0.3,
      c: colors[i % colors.length],
    });
  }
  if (!raf) raf = requestAnimationFrame(tick);
}
function tick() {
  ctx.clearRect(0, 0, cv.width, cv.height);
  parts.forEach((p) => {
    p.x += p.vx * devicePixelRatio;
    p.y += p.vy * devicePixelRatio;
    p.r += p.vr;
    ctx.save();
    ctx.translate(p.x, p.y);
    ctx.rotate(p.r);
    ctx.fillStyle = p.c;
    ctx.fillRect(-p.w / 2, -p.h / 2, p.w, p.h);
    ctx.restore();
  });
  parts = parts.filter((p) => p.y < cv.height + 30);
  raf = parts.length ? requestAnimationFrame(tick) : 0;
  if (!parts.length) ctx.clearRect(0, 0, cv.width, cv.height);
}
