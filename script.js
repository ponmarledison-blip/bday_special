let actx = null,
  playing = false;
function playTune() {
  const AC = window.AudioContext || window.webkitAudioContext;
  if (playing || !AC) return;
  actx = actx || new AC();
  if (actx.resume) actx.resume();
  playing = true;
  const btn = $("tune");
  btn.disabled = true;
  const hz = {
    G4: 392,
    A4: 440,
    B4: 493.88,
    C5: 523.25,
    D5: 587.33,
    E5: 659.25,
    F5: 698.46,
    G5: 783.99,
  };
  const song = [
    ["G4", 0.75],
    ["G4", 0.25],
    ["A4", 1],
    ["G4", 1],
    ["C5", 1],
    ["B4", 2],
    ["G4", 0.75],
    ["G4", 0.25],
    ["A4", 1],
    ["G4", 1],
    ["D5", 1],
    ["C5", 2],
    ["G4", 0.75],
    ["G4", 0.25],
    ["G5", 1],
    ["E5", 1],
    ["C5", 1],
    ["B4", 1],
    ["A4", 1],
    ["F5", 0.75],
    ["F5", 0.25],
    ["E5", 1],
    ["C5", 1],
    ["D5", 1],
    ["C5", 2],
  ];
  const beat = 0.42;
  let t = actx.currentTime + 0.05;
  song.forEach(([n, b]) => {
    const o = actx.createOscillator(),
      g = actx.createGain();
    o.type = "triangle";
    o.frequency.value = hz[n];
    g.gain.setValueAtTime(0.0001, t);
    g.gain.linearRampToValueAtTime(0.25, t + 0.03);
    g.gain.exponentialRampToValueAtTime(0.001, t + b * beat - 0.02);
    o.connect(g);
    g.connect(actx.destination);
    o.start(t);
    o.stop(t + b * beat);
    t += b * beat;
  });
  setTimeout(
    () => {
      playing = false;
      btn.disabled = false;
    },
    (t - actx.currentTime) * 1000 + 200,
  );
}
$("tune").addEventListener("click", playTune);

