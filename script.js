/* Cards */
function cardHTML(f, i, hide) {
  const photo = f.photo
    ? `<img src="${esc(f.photo)}" alt="Photo from ${esc(f.name)}">`
    : placeholder;
  const tilt = i % 2 === 0 ? -2.2 : 2.2,
    tape = i % 2 === 0 ? 4 : -4;
  return `<article class="card${hide ? " hide" : ""}"><figure class="polaroid" style="--tilt:${tilt}deg;--tape:${tape}deg"><div class="photo">${photo}</div><figcaption>${esc(f.nickname)}</figcaption></figure><div class="note"><p class="msg">${esc(f.message)}</p><div class="note-foot"><p class="from">from ${esc(f.name)}</p><button class="like" aria-label="Send a flower to ${esc(f.name)}"><span aria-hidden="true">✿</span> Aww</button></div></div></article>`;
}

function attachTilt(el) {
  if (!matchMedia("(hover: hover)").matches) return;
  el.addEventListener("pointermove", (e) => {
    const r = el.getBoundingClientRect();
    el.style.setProperty(
      "--rx",
      -((e.clientY - r.top) / r.height - 0.5) * 10 + "deg",
    );
    el.style.setProperty(
      "--ry",
      ((e.clientX - r.left) / r.width - 0.5) * 12 + "deg",
    );
  });
  el.addEventListener("pointerleave", () => {
    el.style.setProperty("--rx", "0deg");
    el.style.setProperty("--ry", "0deg");
  });
}

