/* Tap flowers */
function pop(x, y, dx, size) {
  if (REDUCED) return;
  const s = document.createElement("span");
  s.className = "pop";
  s.textContent = "✿";
  s.style.cssText = `left:${x}px;top:${y}px;--dx:${dx}px;font-size:${size}px`;
  document.body.appendChild(s);
  s.addEventListener("animationend", () => s.remove());
}
